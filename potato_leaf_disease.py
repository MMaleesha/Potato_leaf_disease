import matplotlib.pyplot as plt
import math

def plot_images(dataset, class_name, num_images=25, nrows=5, ncols=5):
    # Get the index of the class
    class_index = dataset.class_names.index(class_name)

    # Calculate the total number of images to plot, limited by num_images
    total_images_to_plot = min(num_images, nrows * ncols)

    fig = plt.figure(figsize=(2 * ncols, 2 * nrows))
    fig.suptitle(f'Sample images for class: {class_name}', fontsize=16)

    image_count = 0
    for images, labels in dataset:
        class_images = images[labels.numpy() == class_index]
        for image in class_images:
            if image_count < total_images_to_plot:
                ax = plt.subplot(nrows, ncols, image_count + 1)
                plt.imshow(image.numpy().astype("uint8"))
                plt.title(class_name)
                plt.axis("off")
                image_count += 1
            else:
                plt.tight_layout()
                plt.show()
                return
    plt.tight_layout()
    plt.show()

