import numpy as np
from sklearn.metrics import confusion_matrix
import seaborn as sns

def get_true_and_predicted(model, dataset):
    y_true, y_pred = [], []
    for images, labels in dataset:
        preds = model.predict(images, verbose=0)
        y_true.extend(labels.numpy())
        y_pred.extend(np.argmax(preds, axis=1))
    return np.array(y_true), np.array(y_pred)

cnn_true, cnn_pred = get_true_and_predicted(model, test_ds)
vgg_true, vgg_pred = get_true_and_predicted(vgg16_model, test_ds)
mob_true, mob_pred = get_true_and_predicted(mobilenet_model, test_ds)

fig, axes = plt.subplots(1, 3, figsize=(20, 6))

