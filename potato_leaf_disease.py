"""# VGG16 Model

# VGG16 Transfer Learning Model
"""

from tensorflow.keras.applications import VGG16
from tensorflow.keras.applications.vgg16 import preprocess_input

IMAGE_SIZE = 256
CHANNELS = 3
n_classes = 7

# Load VGG16 pretrained on ImageNet, without the top classification layers
base_model = VGG16(
    weights='imagenet',
    include_top=False,
    input_shape=(IMAGE_SIZE, IMAGE_SIZE, CHANNELS)
)

# Freeze the base model so pretrained weights aren't updated during initial training
base_model.trainable = False

"""# 2. Preprocessing Layer for VGG16"""

vgg_preprocess = tf.keras.layers.Lambda(preprocess_input)

data_augmentation = tf.keras.Sequential([
    layers.RandomFlip("horizontal_and_vertical"),
    layers.RandomRotation(0.2),
    layers.RandomZoom(0.2),
])

"""# 3. Build the Full Model"""

vgg16_model = models.Sequential([
    layers.Resizing(IMAGE_SIZE, IMAGE_SIZE),
    data_augmentation,
    vgg_preprocess,

    base_model,

    layers.GlobalAveragePooling2D(),
    layers.Dense(128, activation='relu'),
    layers.Dropout(0.4),
    layers.Dense(n_classes, activation='softmax'),
])

vgg16_model.build(input_shape=(None, IMAGE_SIZE, IMAGE_SIZE, CHANNELS))
vgg16_model.summary()

"""# 4. Compile the Model"""

vgg16_model.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=0.0001),
    loss=tf.keras.losses.SparseCategoricalCrossentropy(from_logits=False),
    metrics=['accuracy']
)

"""# 5. Train"""

EPOCHS = 10

history_vgg16 = vgg16_model.fit(
    train_ds,
    epochs=EPOCHS,
    validation_data=val_ds,
    verbose=1
)

"""# 6. Fine-Tune"""

# Unfreeze the base model
base_model.trainable = True

# Freeze all layers except the last 4 (last conv block)
for layer in base_model.layers[:-4]:
    layer.trainable = False

# Recompile with a much lower learning rate for fine-tuning
